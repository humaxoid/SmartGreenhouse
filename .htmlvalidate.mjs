// Настройки html-validate для панели контроллера (data/*.html).
//
// Базовый набор правил инструмента рассчитан на обычные сайты, поэтому часть
// из них для встроенной панели неприменима. Отключаем только то, что осознанно
// сделано иначе, с указанием причины — остальное должно оставаться включённым,
// иначе прогон перестанет что-либо значить.
export default {
    extends: ['html-validate:recommended'],
    rules: {
        // Инлайновые стили: панель расставляет значения из JS (высота шкал,
        // углы форточек, цвет индикаторов). Переносить их в style.css некуда —
        // значения меняются в рантайме.
        'no-inline-style': 'off',

        // Плитки выбора темы — <button role="radio"> со своим оформлением:
        // нативный <input type="radio"> не даёт нужного вида превью темы.
        // Роли и aria-checked проставлены вручную, доступность не теряется.
        'prefer-native-element': 'off',

        // Боковое меню и вкладки настроек пока без aria-label: подписи в панели
        // двуязычные, а перевод сейчас умеет только текст элементов, не атрибуты.
        // Держим предупреждением, чтобы не забыть, когда перевод научится атрибутам.
        'unique-landmark': 'warn',
    },
};
