#pragma once
// ╔══════════════════════════════════════════════════════════════════╗
// ║  timer_scheduler.h — Таймеры автоматического полива v5.0        ║
// ║                                                                  ║
// ║  Управляет 3 реле полива (RELAY_IDX_IRR1..3) в auto-режиме.     ║
// ║                                                                  ║
// ║  Каждый таймер имеет:                                            ║
// ║   • startMin       — время первого запуска (минут от полуночи)  ║
// ║   • durationMin    — длительность полива                        ║
// ║   • intervalHours  — период повторения (0 = раз в сутки)        ║
// ║                                                                  ║
// ║  Восстановление после reboot:                                    ║
// ║   Если timerActiveStartSec[i] != -1 — полив был активен,        ║
// ║   продолжаем с остатком времени.                                 ║
// ╚══════════════════════════════════════════════════════════════════╝

#include <stdint.h>
#include <stdbool.h>

namespace TimerSched {

    // Вызвать в setup() после settingsLoad().
    // НЕ запускает полив — только инициализирует внутреннее состояние.
    // Реальная работа начинается после onTimeAvailable().
    void init();

    // Вызывается из taskCore1 при первой синхронизации NTP.
    // После этого таймеры могут реально запускать полив.
    void onTimeAvailable();

    // Основной цикл. Вызывать каждый цикл taskCore1 (~50 мс).
    // Проверяет, не пора ли запустить/остановить полив.
    void update(uint64_t nowMs);

    // Активен ли таймер idx (полив сейчас идёт)?
    // idx: 0..NUM_IRRIGATION-1
    bool isActive(uint8_t timerIdx);

    // Принудительное выключение активного таймера (из кнопки/веба).
    // Таймер возвращается в IDLE, реле выключается, NVS обновляется.
    void onModeChanged(bool autoMode);  // v6.0: пересчёт состояния при смене режима
    void forceOff(uint8_t timerIdx);

    // Сколько секунд осталось до окончания полива (если активен).
    // Возвращает 0 если не активен.
    uint32_t getRemainingSec(uint8_t timerIdx);

    // Когда следующий запуск (секунды от полуночи).
    // -1 если не удаётся вычислить (NTP не синхронизирован или таймер не настроен).
    int32_t getNextStartSec(uint8_t timerIdx);

}  // namespace TimerSched
