#pragma once
// ╔══════════════════════════════════════════════════════════════════╗
// ║  telemetry.h — анонимная статистика разработчику v6.3            ║
// ║                                                                  ║
// ║  ВЫКЛЮЧЕНА по умолчанию. Включается владельцем тумблером в       ║
// ║  «Настройки → Система» и только если в сборку вписан адрес       ║
// ║  приёмника (TELEMETRY_URL в config.h или -DTELEMETRY_URL=...).   ║
// ║                                                                  ║
// ║  Раз в час контроллер шлёт на приёмник по HTTPS одно сообщение:  ║
// ║  идентификатор устройства, версия прошивки, дата установки,      ║
// ║  время работы, часовой пояс, причина последнего запуска,         ║
// ║  минимум свободной памяти, включён ли MQTT, адрес в локальной    ║
// ║  сети. ВНЕШНИЙ IP и страну определяет приёмник по самому         ║
// ║  соединению — контроллер их не знает и не отправляет.            ║
// ║                                                                  ║
// ║  Не отправляются: имя и пароль Wi-Fi, пароли панели и MQTT,      ║
// ║  показания датчиков, состояние реле. Точный список — в README    ║
// ║  и в панели (кнопка «Что отправляется»).                         ║
// ╚══════════════════════════════════════════════════════════════════╝

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

namespace Telemetry {

    // Вызвать один раз в setup() после settingsLoad().
    void init();

    // Есть ли в сборке адрес приёмника. Если нет — тумблер недоступен.
    bool isAvailable();

    bool isEnabled();
    void setEnabled(bool on);

    // Идентификатор устройства: 16 hex-символов, SHA-256 от заводского
    // MAC (eFuse) с солью проекта. Постоянен всю жизнь платы, MAC не раскрывает.
    const char* deviceId();

    // Тело сообщения — ровно то, что уходит на приёмник (для показа в панели).
    // Возвращает длину или 0 при нехватке места.
    size_t buildPayload(char* out, size_t outSize, bool boot);

    // Состояние последней отправки для панели.
    struct Status {
        uint32_t lastOkTs;     // Unix-время последней удачной отправки, 0 — не было
        int16_t  lastCode;     // HTTP-код или отрицательный код ошибки клиента
        uint32_t sent;         // удачных отправок с запуска
    };
    Status status();

    // Только из loopTask: отправка блокирует на время TLS-соединения (до ~6 с).
    void loop(uint64_t nowMs);

    // Адрес приёмника (для показа в панели), пустая строка — не задан.
    const char* url();

}  // namespace Telemetry
