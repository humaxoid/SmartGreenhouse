#include <stdint.h>
#include <stdbool.h>

namespace WaterPumpCtrl {

    // Вызывать каждый цикл (~1 сек).
    // waterLevelPct — текущий уровень воды в ёмкости, % [0..100]. NaN = датчик недоступен.
    void update(float waterLevelPct);

    // Находится ли насос в состоянии "аварийной блокировки"
    // (был выключен по таймауту, ждёт сброса).
    bool isInFault();

    // Сброс аварийной блокировки — вызывается из веб-панели
    // кнопкой "сбросить аварию насоса".
    void resetFault();

}  // namespace WaterPumpCtrl
