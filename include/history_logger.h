#pragma once
// ╔══════════════════════════════════════════════════════════════════╗
// ║  history_logger.h — История данных для графиков v5.0            ║
// ║                                                                  ║
// ║  Сохраняет снимок каждого датчика раз в HISTORY_INTERVAL_MS     ║
// ║  (1 час по умолчанию). Хранит последние HISTORY_POINTS (24).    ║
// ║  Буфер кольцевой, персистентность через LittleFS.               ║
// ║                                                                  ║
// ║  Используется веб-интерфейсом для построения графиков суточной  ║
// ║  динамики: температура, влажность, освещённость, уровень воды.  ║
// ╚══════════════════════════════════════════════════════════════════╝

#include "config.h"
#include <stdint.h>
#include <stdbool.h>
#include <time.h>

// ─── Одна точка истории v6.0 ─────────────────────────────────────
// Размер: 4 (time) + 7*4 (float) = 32 байта.
// 24 точки × 32 байта = 768 байт в RAM.
// v6.0: добавлены поля dhtTemp, dhtHumidity для построения графиков
// "внутри (BME280) vs снаружи (DHT22)".
struct HistoryPoint {
    time_t   timestamp;     // Unix timestamp (сек). 0 = слот пуст.
    float    temp;          // BME280 °C (NAN если недоступно) — внутри теплицы
    float    humidity;      // BME280 % — внутри теплицы
    float    pressure;      // BME280 мм рт. ст.
    float    lux;           // Освещённость BH1750
    float    waterLevel;    // % (AJ-SR04M)
    float    dhtTemp;       // DHT22 °C — снаружи теплицы (v6.0)
    float    dhtHumidity;   // DHT22 % — снаружи (v6.0)
};


namespace HistoryLogger {

    // Вызывается в setup() после LittleFS.begin().
    // Загружает историю из файла если есть, иначе создаёт пустую.
    void init();

    // Вызывается из taskCore1 при первой NTP-синхронизации.
    // Начинает периодическое логирование.
    void onTimeAvailable();

    // Основной цикл. Вызывается из taskCore1.
    // Проверяет, не пора ли записать новую точку.
    void update(uint64_t nowMs);

    // Получить массив всех валидных точек (упорядочено по времени).
    // Результат записывается в outPoints, возвращается количество валидных.
    // Максимум HISTORY_POINTS точек.
    uint8_t getAll(HistoryPoint* outPoints, uint8_t maxPoints);

    // Очистить историю (команда из веб-панели "сбросить графики")
    void clear();

}  // namespace HistoryLogger
