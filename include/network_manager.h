#include "config.h"
#include <stdint.h>
#include <stdbool.h>

// ─── Настройки сети из NVS ────────────────────────────────────────
struct NetCache {
    bool isDHCP;
    char ssid[33];         // IEEE 802.11 ограничение: 32 + '\0'
    char pass[64];         // WPA2: до 63 символов + '\0'
    char ip[16];           // "xxx.xxx.xxx.xxx"
    char subnet[16];
    char gateway[16];
    char dns1[16];
    char dns2[16];
    char webUser[32];
    char webPass[32];
};

namespace NetMgr {

    // ═══════════════════════════════════════════════════════════════
    //  ИНИЦИАЛИЗАЦИЯ И УПРАВЛЕНИЕ WI-FI
    // ═══════════════════════════════════════════════════════════════

    // Загрузка NetCache из NVS, регистрация Wi-Fi event handler.
    // Не подключается к Wi-Fi — только подготовка.
    void init();

    // Проверка наличия учётных данных Wi-Fi в NVS.
    // Используется main.cpp для решения: идём в STA или поднимаем AP.
    bool hasCredentials();

    // Попытка подключения к сохранённому Wi-Fi (STA mode).
    // Блокирующая — ждёт до WIFI_STA_TIMEOUT_MS или успешного IP.
    // Возвращает true, если получили IP.
    bool connectSTA();

    // Запуск фоновой задачи переподключения Wi-Fi на Core 0.
    // Реагирует на события DISCONNECTED с exponential backoff.
    void startWifiTask();

    // Текущий статус подключения Wi-Fi (не NTP!)
    bool isConnected();

    // ═══════════════════════════════════════════════════════════════
    //  АВАРИЙНАЯ ТОЧКА ДОСТУПА (v6.1)
    // ═══════════════════════════════════════════════════════════════
    // Поднимается, когда учётные данные есть, но подключиться не вышло —
    // например, при опечатке в пароле Wi-Fi. Режим AP_STA: контроллер
    // продолжает попытки подключиться к домашней сети и одновременно
    // доступен напрямую по адресу 192.168.4.1.
    //
    // Это НЕ режим первоначальной настройки (WifiProv): свой веб-сервер
    // и DNS не поднимаются, работает обычная панель со всеми настройками.
    // Автоматика теплицы продолжает работать без ограничений.
    //
    // Гасится автоматически, как только STA получит IP.
    void startRescueAp();
    void stopRescueAp();
    bool isRescueApActive();

    // Данные сети из NVS
    const NetCache& cache();

    // Base64 токен "user:pass" для HTTP Basic Auth
    const char* wsToken();

    // ═══════════════════════════════════════════════════════════════
    //  NTP
    // ═══════════════════════════════════════════════════════════════

    // Инициализация SNTP из настроек g_settings (сервер, TZ, интервал).
    // Вызывать ПОСЛЕ settingsLoad().
    void initNtp();

    // Пересборка SNTP (при изменении настроек через веб).
    void reinitNtp();

    // Было ли первое успешное получение времени с сервера?
    // Выставляется в коллбэке sntp_set_time_sync_notification_cb.
    bool isTimeSet();

    // Зарегистрировать коллбэк "первая синхронизация NTP".
    // Используется для отложенной инициализации таймеров полива
    // (они требуют реальное время).
    void setOnFirstTimeSet(void (*cb)());

    // Геттеры времени. Возвращают локальное время (согласно TZ).
    // Если NTP ещё не синхронизирован — возвращают -1 (час/мин) или 0 (сек).
    int  getHour();
    int  getMinute();
    int  getSecond();

    // "HH:MM:SS" в статическом буфере
    const char* getFormattedTime();

    // ═══════════════════════════════════════════════════════════════
    //  СОХРАНЕНИЕ НАСТРОЕК (из веб-панели)
    // ═══════════════════════════════════════════════════════════════

    // v6.1: возвращает false, если хотя бы одно поле не записалось в NVS.
    // Раньше результат было негде взять: кэш в RAM обновлялся всегда, и
    // проваленная запись выглядела снаружи как успешная.
    bool saveNetSettings(const NetCache& nc, bool savePass);

    // Стирает SSID и пароль Wi-Fi так, чтобы после перезагрузки контроллер
    // ушёл в режим первоначальной настройки. Возвращает false, если после
    // всех попыток учётные данные в NVS уцелели.
    bool clearWifiCredentials();
    void saveWebCreds(const char* user, const char* pass);

}  // namespace NetMgr
