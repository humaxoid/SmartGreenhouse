// ─── Конфигурация одного таймера полива ──────────────────────────
struct TimerCfg {
    uint16_t startMin;       // Время старта: минуты от полуночи [0..1439]
    uint16_t durationMin;    // Длительность полива, мин
    uint16_t intervalHours;  // Период повторения, ч
};

// ─── Пороги гистерезиса форточки по температуре ──────────────────
// Используются в auto-режиме для расчёта ЦЕЛЕВОЙ позиции
// (0% при T<=low, 100% при T>=high, линейная интерполяция между).
struct VentThresh {
    float high;   // T, при которой форточка полностью открыта (100%)
    float low;    // T, при которой форточка полностью закрыта (0%)
};

// ─── Калибровка H-bridge форточки ────────────────────────────────
// Позволяет подстроить время движения под конкретный актуатор,
// который может отличаться от номинала из-за температуры,
// износа, нагрузки и т.п. Значения корректируются через веб-панель.
struct VentCalibration {
    // v6.1: uint16_t → uint32_t. Раньше значения > 65535 мс (65 сек) молча
    // переполнялись, хотя и веб-форма, и WS-команды разрешают до 120 сек.
    uint32_t travelMs;       // Полное время хода, мс (напр. 42000)
    uint16_t overrunPct;     // Запас при достижении концевика, % (обычно 10)
    // Примечание: таймаут движения = travelMs * (100 + overrunPct) / 100
};

// ─── Персистентное состояние форточки ────────────────────────────
// Хранится в NVS, восстанавливается при старте. Позволяет форточке
// вернуться в ту же позицию после кратковременного отключения питания.
//
// ВАЖНО: при долгом отключении питания (>1 часа) позиция может стать
// неактуальной (актуатор держит положение механически, но мог сместиться).
// Для таких случаев используем автокалибровку ночью.
struct VentPersistent {
    uint8_t lastKnownPct;    // Последняя известная позиция, % [0..100]
    // Доп. флаг: "позиция валидна" vs "требует калибровки"
    // 0 = нужна калибровка (например, после полного отключения),
    // 1 = позиция достоверна
    uint8_t positionValid;
};

// ─── Настройки накопительной ёмкости (насос скважины) ────────────
struct WaterTankCfg {
    uint8_t  lowPct;         // Включить насос при уровне < lowPct %
    uint8_t  highPct;        // Выключить насос при уровне > highPct %
    uint16_t depthCm;        // Глубина ёмкости, см
    uint16_t pumpTimeoutMin; // Таймаут непрерывной работы насоса, мин
};

// ═══════════════════════════════════════════════════════════════════
//  ГЛАВНАЯ СТРУКТУРА НАСТРОЕК
// ═══════════════════════════════════════════════════════════════════
// ВАЖНО: при добавлении новых полей увеличивай AppSettingsVersion.
// settingsLoad() проверяет версию и при несовпадении применяет defaults.
// Это защищает от "мусорных" данных при обновлении прошивки.

#define APP_SETTINGS_VERSION  7   // v6.1: VentCalibration.travelMs uint16 → uint32

struct AppSettings {
    // ── Версия структуры (для миграции при обновлении прошивки) ──
    uint8_t    settingsVersion;

    // ── Режимы (0 = ручной, 1 = автоматический) ──────────────────
    uint8_t    modeVents;         // Форточки (обе)
    uint8_t    modeTimers;        // Таймеры полива
    uint8_t    modeHumid;         // Увлажнитель
    uint8_t    modeWaterPump;     // Насос скважины

    // ── Состояния реле (9 штук — запоминаются для восстановления) ──
    // Индексы соответствуют RELAY_IDX_* из config.h.
    // ВНИМАНИЕ: для H-bridge форточек реле OPEN и CLOSE НЕ
    // восстанавливаются "в лоб" после перезагрузки — мы восстанавливаем
    // только позицию форточки (см. ventPersistent ниже), а реле всегда
    // стартуют в состоянии OFF (ступор = позиция зафиксирована).
    bool       relayState[NUM_RELAYS];

    // ── Таймеры полива (3 шт.) ──────────────────────────────────
    TimerCfg   timer[NUM_IRRIGATION];
    // Время начала активного полива (секунды от полуночи), -1 = не активен.
    // Сохраняется в NVS при старте/остановке полива — для восстановления
    // при перезагрузке посреди полива.
    int32_t    timerActiveStartSec[NUM_IRRIGATION];

    // ── Форточки: пороги по температуре ──────────────────────────
    VentThresh ventUpper;         // Верхняя форточка
    VentThresh ventLower;         // Нижняя форточка

    // ── Форточки: калибровка хода H-bridge ───────────────────────
    VentCalibration ventUpperCal; // Верхняя: время хода 42 сек ± корректировка
    VentCalibration ventLowerCal; // Нижняя:  время хода 24 сек ± корректировка

    // ── Форточки: персистентное состояние (позиция) ──────────────
    VentPersistent  ventUpperPos; // Последняя известная позиция верхней, %
    VentPersistent  ventLowerPos; // Последняя известная позиция нижней, %

    // ── Увлажнитель: пороги влажности ────────────────────────────
    float      humidHigh;         // Выключить при H >= high
    float      humidLow;          // Включить  при H <= low

    // ── Ёмкость/насос ────────────────────────────────────────────
    WaterTankCfg waterTank;

    // ── NTP (изменяемые через веб) ───────────────────────────────
    // v5.0: теперь это POSIX TZ string, а не часовой пояс в часах.
    // Пример: "MSK-3", "EST5EDT,M3.2.0,M11.1.0"
    char    ntpServer[64];
    char    ntpTzString[48];     // POSIX TZ, например "MSK-3"
    uint8_t ntpUpdateHrs;        // Интервал синхронизации, ч

    // ── MQTT настройки ───────────────────────────────────────────
    char     mqttServer[64];
    uint16_t mqttPort;
    char     mqttUser[32];
    char     mqttPass[32];
    bool     mqttEnabled;

    // ── UI настройки (v6.0) ──────────────────────────────────────
    // Хранятся в NVS: тема применяется сразу при загрузке из первого snapshot.
    // uiTheme: "" | "beige" | "night" | "win98" | "skyblue" | "brown"
    // uiLang:  "en" | "ru"
    char     uiTheme[16];
    char     uiLang[8];
};

// ═══════════════════════════════════════════════════════════════════
//  ЭФЕМЕРНОЕ (не персистентное) СОСТОЯНИЕ H-BRIDGE ФОРТОЧЕК
// ═══════════════════════════════════════════════════════════════════
// Эти данные обновляются во время работы, НЕ хранятся в NVS, и
// инициализируются при старте исходя из VentPersistent. Они живут
// в памяти и доступны всем модулям (ws_handler показывает состояние,
// vent_controller управляет движением).

// Направление движения форточки
enum VentDirection : uint8_t {
    VENT_DIR_STOPPED = 0,   // Стоп, оба реле OFF
    VENT_DIR_OPENING = 1,   // Движение на открытие (реле OPEN = ON)
    VENT_DIR_CLOSING = 2    // Движение на закрытие (реле CLOSE = ON)
};

struct VentRuntime {
    // Текущая позиция в процентах [0..100]. Обновляется в VentCtrl::update()
    // исходя из прошедшего времени движения.
    // float, а не uint8_t — чтобы точность накопления была высокой
    // (1% для верхней = 420 мс, с uint8_t каждый цикл было бы округление).
    float   currentPct;

    // Целевая позиция, % [0..100]. Задаётся либо авто-логикой по
    // температуре, либо вручную через веб или кнопку.
    float   targetPct;

    // Направление движения прямо сейчас
    VentDirection direction;

    // Время начала текущего движения (мс). 0 = не движется.
    uint64_t moveStartMs;

    // Время последнего изменения направления (для break-before-make)
    uint64_t lastDirChangeMs;

    // Флаг: позиция требует калибровки (home). Устанавливается при
    // старте ESP32 если positionValid = 0 в NVS, или раз в сутки в 3:00.
    bool     needsCalibration;

    // Флаг: идёт процесс калибровки (движение до нижнего концевика).
    bool     calibrating;
};

