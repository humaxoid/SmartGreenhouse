// Загрузка настроек из NVS. Если NVS пустой или версия не совпадает —
// применяет дефолты. Должна вызываться ОДИН раз в setup() ДО создания
// задач FreeRTOS.
void settingsLoad();

// Атомарное сохранение ВСЕХ настроек в NVS. Блокирующая операция
// (запись в flash занимает 5-50 мс), поэтому её вызывает taskCore1
// по истечении NVS_SAVE_DELAY_MS после последнего settingsSaveDeferred().
void settingsSave();

// Помечает настройки как изменённые. Фактическое сохранение произойдёт
// отложенно (через NVS_SAVE_DELAY_MS) — защита от износа flash при
// быстрых изменениях (например, слайдер форточки шлёт 20 событий в сек).
void settingsSaveDeferred();

// Сколько раз настройки РЕАЛЬНО записывались во флеш с момента старта.
// v6.1: settingsSave() пропускает запись, если содержимое не изменилось,
// поэтому счётчик показывает фактическую нагрузку на флеш, а не число
// вызовов. Выводится в строке [HEALTH] — по нему видно, не молотит ли
// какая-нибудь подсистема запись без нужды.
uint32_t settingsNvsWriteCount();

// Сброс к заводским настройкам (применяет defaults и сохраняет).
// Используется при первом запуске или при действии пользователя
// "factory reset" через веб.
void settingsReset();

// Инициализация g_ventRuntime на основе g_settings. Вызывается после
// settingsLoad(). Если positionValid=1, восстанавливает позицию;
// иначе ставит флаг needsCalibration для calibration-routine.
void ventRuntimeInit();
