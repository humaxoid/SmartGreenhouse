// ═══════════════════════════════════════════════════════════════════
//  ВСПОМОГАТЕЛЬНЫЙ RAII-ЗАХВАТ МЬЮТЕКСА
// ═══════════════════════════════════════════════════════════════════
// Использование: MutexGuard lock(g_settingsMutex, pdMS_TO_TICKS(50));
//                if (lock.locked()) { ... }
// v6.1: гард работает с РЕКУРСИВНЫМ мьютексом (xSemaphoreCreateRecursiveMutex).
// Причина: в коде много мест вида "взяли лок → вызвали setRelay()/settingsSave(),
// которые берут тот же лок". С обычным мьютексом FreeRTOS повторный захват из той
// же задачи не проходит и молча отваливается по таймауту — реле не переключалось,
// настройки не сохранялись. Рекурсивный лок делает такие вложенные вызовы корректными.
//
// ВАЖНО: передавать сюда можно ТОЛЬКО мьютексы, созданные через
// xSemaphoreCreateRecursiveMutex(). Для обычных мьютексов (s_mutex в
// sensor_reader/history_logger) используется прямой xSemaphoreTake.
class MutexGuard {
public:
    explicit MutexGuard(SemaphoreHandle_t m, TickType_t ticks = pdMS_TO_TICKS(100))
        : _m(m), _taken(xSemaphoreTakeRecursive(m, ticks) == pdTRUE) {}
    ~MutexGuard() { if (_taken) xSemaphoreGiveRecursive(_m); }
    bool locked() const { return _taken; }
    // Запрет копирования/перемещения — RAII-объект должен жить в своём скоупе
    MutexGuard(const MutexGuard&) = delete;
    MutexGuard& operator=(const MutexGuard&) = delete;
private:
    SemaphoreHandle_t _m;
    bool              _taken;
};

