#pragma once
// ╔══════════════════════════════════════════════════════════════════╗
// ║  relay_manager.h — Управление 9 реле с H-bridge логикой         ║
// ║  v5.0                                                            ║
// ║                                                                  ║
// ║  Реализует:                                                      ║
// ║   • Управление одиночными реле (полив, увлажнитель, насос)      ║
// ║   • Управление парами H-bridge (форточки)                       ║
// ║   • Антидребезг (не чаще RELAY_MIN_TOGGLE_INTERVAL_MS)          ║
// ║   • Interlock H-bridge (OPEN+CLOSE никогда одновременно)        ║
// ║   • Break-before-make (пауза при смене направления)             ║
// ║   • Атомарное обновление g_settings.relayState[] под мьютексом  ║
// ╚══════════════════════════════════════════════════════════════════╝

#include "config.h"
#include "settings.h"   // VentDirection
#include <stdint.h>
#include <stdbool.h>

namespace RelayMgr {

    // ═══════════════════════════════════════════════════════════════
    //  ИНИЦИАЛИЗАЦИЯ
    // ═══════════════════════════════════════════════════════════════

    // Настройка всех GPIO как OUTPUT, все реле в OFF. Также инициализирует
    // GPIO2 (heartbeat LED). Вызывать ОДИН раз в setup() ДО загрузки
    // настроек (т.к. реле должны быть в безопасном состоянии с первой мс).
    void init();

    // Восстановление состояний одиночных реле из g_settings.relayState[].
    // Вызывать ПОСЛЕ settingsLoad().
    // Реле форточек (H-bridge) НЕ восстанавливаются — они всегда стартуют
    // в состоянии STOP (оба OFF), позиция берётся из g_ventRuntime.
    void restoreFromSettings();

    // ═══════════════════════════════════════════════════════════════
    //  API ДЛЯ ОДИНОЧНЫХ РЕЛЕ
    // ═══════════════════════════════════════════════════════════════
    // Используется для: полива (3 реле), увлажнителя, насоса.
    // НЕ ИСПОЛЬЗОВАТЬ для реле форточек (индексы 3-6)!
    // Используй вместо этого moveVent()/stopVent().

    // Установить состояние реле. Возвращает true, если состояние
    // реально изменилось; false — если реле уже было в этом состоянии
    // ИЛИ если сработал антидребезг (слишком рано после предыдущего
    // переключения) ИЛИ если это реле из H-bridge пары (используй moveVent).
    //
    // Под мьютексом g_settingsMutex обновляет g_settings.relayState[idx]
    // и вызывает settingsSaveDeferred().
    //
    // MQTT публикация нового состояния происходит здесь же.
    bool setRelay(uint8_t idx, bool on);

    // Получить текущее состояние реле (читает из g_settings.relayState[]).
    // Быстрая операция — используется в отладке и при broadcast WS.
    bool getState(uint8_t idx);

    // Человекочитаемое имя реле для Serial-лога ("Полив 1", "Верх. OPEN", ...)
    const char* getName(uint8_t idx);

    // ═══════════════════════════════════════════════════════════════
    //  API ДЛЯ H-BRIDGE ФОРТОЧЕК
    // ═══════════════════════════════════════════════════════════════

    // Запустить движение форточки в указанном направлении.
    // Безопасная последовательность:
    //   1. Если противоположное реле включено — выключить его
    //   2. Подождать HBRIDGE_BREAK_BEFORE_MAKE_MS (не блокирует задачу!
    //      используется неблокирующая задержка — см. реализацию)
    //   3. Включить нужное реле
    //
    // ВАЖНО: эта функция НЕ блокирует! Она разбивает операцию на этапы
    // через конечный автомат (см. updatePending()). Задача (taskCore1)
    // должна периодически вызывать updatePending() для выполнения
    // отложенных переключений.
    //
    // ventIdx: VENT_IDX_UPPER или VENT_IDX_LOWER
    // dir: VENT_DIR_OPENING, VENT_DIR_CLOSING или VENT_DIR_STOPPED
    //
    // Возвращает true, если команда принята к исполнению.
    bool moveVent(uint8_t ventIdx, VentDirection dir);

    // Мгновенная остановка форточки — оба реле пары OFF.
    // Используется при достижении позиции, аварии, перезагрузке.
    // Break-before-make тут не нужен (переходим в безопасное состояние).
    bool stopVent(uint8_t ventIdx);

    // Получить текущее направление движения форточки.
    // Читается атомарно из g_ventRuntime[ventIdx].direction.
    VentDirection getVentDirection(uint8_t ventIdx);

    // ═══════════════════════════════════════════════════════════════
    //  ПЕРИОДИЧЕСКИЙ UPDATE
    // ═══════════════════════════════════════════════════════════════

    // Вызывается из taskCore1 каждый цикл (~50 мс).
    // Выполняет отложенные операции переключения H-bridge
    // (вторая фаза после break-before-make паузы).
    void updatePending(uint64_t nowMs);

    // ═══════════════════════════════════════════════════════════════
    //  HEARTBEAT LED (GPIO2)
    // ═══════════════════════════════════════════════════════════════

    // Переключить LED если прошло LED_HEARTBEAT_PERIOD_MS.
    // Вызывается из taskCore1 каждый цикл.
    void updateHeartbeat(uint64_t nowMs);

    // ═══════════════════════════════════════════════════════════════
    //  ВСПОМОГАТЕЛЬНЫЕ
    // ═══════════════════════════════════════════════════════════════

    // Является ли реле частью H-bridge пары?
    // Нужно для setRelay() — не даём дёргать его напрямую.
    bool isVentRelay(uint8_t idx);

    // По индексу форточки вернуть индекс реле OPEN/CLOSE
    uint8_t ventOpenRelayIdx(uint8_t ventIdx);
    uint8_t ventCloseRelayIdx(uint8_t ventIdx);


    // v6.0: ПРЯМОЕ управление реле (минуя проверку isVentRelay).
    // Использовать ТОЛЬКО из VentCtrl для управления моторами форточек.
    // Антидребезг также пропускается — VentCtrl сам гарантирует
    // корректные временные интервалы.
    bool setRelayDirect(uint8_t idx, bool on);

}  // namespace RelayMgr
