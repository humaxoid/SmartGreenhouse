// ║   • Автокалибровка убрана                                        ║
// ╚══════════════════════════════════════════════════════════════════╝
#pragma once

#include <Arduino.h>
#include <stdint.h>
#include "config.h"

// ─── Типы команд ручного режима ──────────────────────────────────
enum VentManualCmd : uint8_t {
    VMC_NONE  = 0,   // Кнопка не нажата
    VMC_OPEN  = 1,   // Зажата "Открыть" — эстафета верх→низ
    VMC_CLOSE = 2    // Зажата "Закрыть" — эстафета низ→верх
};

// ─── Состояние авто-режима (КАА) ─────────────────────────────────
enum VentAutoState : uint8_t {
    VAS_IDLE              = 0,   // Ожидание изменения температуры
    VAS_OPEN_TOP_STEP     = 1,   // Открываем верхнюю на одну ступень
    VAS_OPEN_BOTTOM_STEP  = 2,   // Открываем нижнюю на одну ступень
    VAS_CLOSE_TOP_STEP    = 3,   // Закрываем верхнюю на одну ступень
    VAS_CLOSE_BOTTOM_STEP = 4,   // Закрываем нижнюю на одну ступень
    VAS_PAUSE_WAIT        = 5,   // Пауза между ступенями (STEP_DELAY_MIN)
    VAS_RAIN_CLOSING      = 6    // Дождь — экстренное закрытие обеих
};

// ─── Снапшот для веб-интерфейса ──────────────────────────────────
struct VentStatusSnapshot {
    uint8_t  topPct;             // Позиция верхней форточки 0..100
    uint8_t  bottomPct;          // Позиция нижней форточки 0..100
    bool     topMoving;          // Верхний актуатор крутит сейчас
    bool     bottomMoving;       // Нижний актуатор крутит сейчас
    int8_t   topDir;             // -1 close, 0 stop, +1 open
    int8_t   bottomDir;
    uint8_t  autoState;          // VentAutoState
    bool     rainBlocked;        // Дождь активен
    uint16_t topCalibSec;        // Калибровка, сек
    uint16_t bottomCalibSec;
    bool     topHoming;          // v6.1: идёт калибровочный прогон
    bool     bottomHoming;
};

namespace VentCtrl {

    // ─── Жизненный цикл ─────────────────────────────────────────
    void init();
    void update(uint64_t nowMs, float temp, bool rain, bool autoMode);

    // ─── Ручной режим ───────────────────────────────────────────
    // cmd = VMC_OPEN/VMC_CLOSE — начать или продолжить эстафету.
    // cmd = VMC_NONE — стоп (отпустили кнопку).
    // Защита: если "удержание" длится > MANUAL_HOLD_TIMEOUT_MS — стоп.
    void manualSetCmd(VentManualCmd cmd);

    // ─── Калибровка (ручной ввод времени хода в секундах) ───────
    bool setTopCalibSec(uint16_t sec);
    bool setBottomCalibSec(uint16_t sec);
    uint16_t getTopCalibSec();
    uint16_t getBottomCalibSec();

    // ─── Информация для веба ────────────────────────────────────
    void getStatus(VentStatusSnapshot& out);

    // ─── Смена режима (auto/manual) ─────────────────────────────
    // При смене режима: останавливаем все моторы, переходим в IDLE.
    void onModeChanged(bool autoMode);

    // ─── Калибровочный прогон (v6.1) ────────────────────────────
    // Гонит привод на ЗАКРЫТИЕ полное время хода плюс запас, не глядя
    // на расчётную позицию, — до упора в концевик. По окончании
    // позиция принудительно обнуляется и сохраняется.
    //
    // Зачем: положение считается по времени работы привода и со временем
    // расходится с реальностью. Штатными средствами это было не исправить:
    // при расчётном нуле привод останавливается, даже если створка ещё
    // приоткрыта, и «дожать» её было нечем. Единственным выходом был
    // сброс к заводским настройкам, стирающий заодно пороги и расписание.
    //
    // side: 0 — верхняя, 1 — нижняя.
    // Возвращает false, если прогон уже идёт или индекс неверный.
    bool startHoming(uint8_t side);

    // Идёт ли сейчас прогон (для отображения в панели).
    bool isHoming(uint8_t side);

    // Прервать прогон досрочно (кнопка «стоп», смена режима, дождь).
    void cancelHoming();


    // ─── Текущая позиция створки, % ─────────────────────────────
    // Используется публикацией состояния в MQTT.
    inline uint8_t getCurrentPosition(uint8_t idx) {
        VentStatusSnapshot vs;
        getStatus(vs);
        return idx == 0 ? vs.topPct : vs.bottomPct;
    }

    // v6.1: удалены заглушки setTargetPosition, forceHomeCalibration,
    // getTargetPosition и isCalibrating. Они остались от версии 5 со
    // слайдером позиции и автокалибровкой; все возвращали false или
    // дублировали getCurrentPosition.
    //
    // Особенно вредной была setTargetPosition: её вызывал обработчик
    // MQTT, из-за чего в Home Assistant у форточек отображался ползунок
    // позиции, молча не делавший ничего. Обработчик и соответствующая
    // часть discovery убраны — HA теперь честно показывает позицию
    // только на чтение.

}  // namespace VentCtrl
