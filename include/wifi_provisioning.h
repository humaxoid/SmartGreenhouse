// ║  Поток работы:                                                   ║
// ║   1. main.cpp: if (!NetMgr::hasCredentials()) WifiProv::start()  ║
// ║   2. Пользователь подключается к "Greenhouse-XXXXXX" (12345678) ║
// ║   3. Захода в браузер → captive portal показывает форму          ║
// ║   4. Пользователь выбирает SSID, вводит пароль                   ║
// ║   5. ESP32 сохраняет в NVS и перезагружается                     ║
// ║   6. При следующем boot идём в STA mode с сохранёнными данными   ║
// ╚══════════════════════════════════════════════════════════════════╝

#include <stdint.h>
#include <stdbool.h>

namespace WifiProv {

    // ═══════════════════════════════════════════════════════════════
    //  API
    // ═══════════════════════════════════════════════════════════════

    // Запустить AP mode + captive portal.
    // После этого ESP32 не возвращается из функции самостоятельно —
    // прошивка крутится в loop() пока пользователь не сохранит настройки.
    // По успеху — сохраняет в NVS через NetMgr::saveNetSettings()
    // и вызывает ESP.restart().
    //
    // ВАЖНО: Этот режим БЛОКИРУЕТ запуск основной бизнес-логики
    // (реле, датчики, MQTT). Но это нормально — без Wi-Fi всё равно
    // ничего не работает осмысленно.
    //
    // ssidPrefix: префикс имени AP (например "Greenhouse-")
    // password: пароль AP (минимум 8 символов для WPA2)
    void start(const char* ssidPrefix, const char* password);

    // Периодическая обработка: вызывать из main loop.
    // Обрабатывает DNS запросы (captive portal).
    // Если loop() не вызывается — DNS хиджак не работает, captive portal ломается.
    void loop();

    // Флаг "мы в режиме AP provisioning"
    bool isActive();

}  // namespace WifiProv
