// ║  mqtt_manager.h — MQTT клиент с Home Assistant discovery v5.0   ║
// ║                                                                  ║
// ║  Главные изменения v5.0:                                         ║
// ║   • Discovery публикуется ТОЛЬКО при реальных изменениях        ║
// ║     (не при каждом reconnect, как в v4)                         ║
// ║   • Новые cover entity для форточек (позиция 0-100%)            ║
// ║   • Публикация состояния FAULT насоса                            ║
// ║   • Совместимо с HA 2024.x и выше                                ║
// ╚══════════════════════════════════════════════════════════════════╝

#include <stdint.h>
#include <stdbool.h>

namespace MqttMgr {

    // ═══════════════════════════════════════════════════════════════
    //  ЖИЗНЕННЫЙ ЦИКЛ
    // ═══════════════════════════════════════════════════════════════

    // Инициализация клиента (не подключается). Регистрирует коллбэки.
    void init();

    // Основной цикл — вызывается из taskCore0 (раз в ~100 мс).
    // Проверяет подключение, при необходимости реконнект,
    // публикует периодические данные, обрабатывает discovery_dirty.
    void loop();

    // Форсированная отправка discovery. Используется при первом
    // подключении или по команде "пересоздать HA entities".
    // НЕ публикует сразу — только выставляет флаг dirty.
    void markDiscoveryDirty();

    // Есть ли соединение с брокером
    bool isConnected();

    // ═══════════════════════════════════════════════════════════════
    //  ПУБЛИКАЦИИ
    // ═══════════════════════════════════════════════════════════════

    // Публикует состояние реле idx в /state. Вызывается автоматически
    // из RelayMgr::setRelay при каждом изменении.
    // НЕ публикует реле форточек (для них используется publishVentState).
    void publishRelayState(uint8_t idx);

    // Публикует позицию форточки как cover (0-100%). Вызывается из
    // VentCtrl после остановки движения.
    void publishVentState(uint8_t ventIdx);

    // Публикует состояние насоса включая FAULT.
    // Вызывается автоматически при изменении state.
    void publishPumpState();

}  // namespace MqttMgr
