// ║  Журнал «что и когда случилось» — два кольца:                    ║
// ║    • важные (запуски, тревоги, отказы, обновления) — EVLOG_IMP; ║
// ║    • обычные (реле, форточки, режимы, настройки) — EVLOG_RTN.   ║
// ║  Раздельные кольца нужны, чтобы рутина не вытесняла тревоги.    ║
// ║  Включения реле, движение форточек, смена режимов, тревоги,     ║
// ║  включения реле, движение форточек, смена режимов, тревоги,     ║
// ║  отказы датчиков, дождь, Wi-Fi, смена настроек, обновления,     ║
// ║  перезагрузки, неудачные входы. Показывается на странице         ║
// ║  «Журнал событий» панели (команда get_events).                   ║
// ║                                                                  ║
// ║  Большинство событий НЕ вызываются из модулей, а собираются      ║
// ║  наблюдателем: раз в секунду он сравнивает состояние (реле,      ║
// ║  режимы, датчики, дождь, насос, Wi-Fi, позиции створок) с        ║
// ║  предыдущим. Так журнал не зависит от того, кто именно — авто-  ║
// ║  матика, кнопка, панель или MQTT — изменил состояние.            ║
// ║                                                                  ║
// ║  Хранение: RAM + копия в NVS (namespace "gevt"), запись не чаще ║
// ║  раза в 10 минут и принудительно перед штатной перезагрузкой.    ║
// ║  При внезапной потере питания теряется не больше 10 минут.       ║
// ╚══════════════════════════════════════════════════════════════════╝

#include <stdint.h>

// Кольца: 32 важных + 48 обычных. Запись — 10 байт, блоб в NVS 808 байт.
#define EVLOG_IMP    32
#define EVLOG_RTN    48
#define EVLOG_SIZE   (EVLOG_IMP + EVLOG_RTN)   // сколько записей отдаёт getAll

// Коды событий — часть протокола с панелью (app.js), не перенумеровывать.
enum EvType : uint8_t {
    EV_BOOT      = 1,   // arg — esp_reset_reason()
    EV_RELAY     = 2,   // arg — индекс реле, val — 1 вкл / 0 выкл
    EV_VENT      = 3,   // arg — створка (0 верх, 1 низ), val — от*256 + до, %
    EV_MODE      = 4,   // arg — 0 форточки, 1 полив, 2 увлажнитель, 3 насос; val — 1 авто / 0 ручной
    EV_PUMP      = 5,   // val — 1 авария насоса / 0 авария снята
    EV_SENSOR    = 6,   // arg — 0 BME280, 1 DHT22, 2 BH1750, 3 AJ-SR04M; val — 1 работает / 0 отказ
    EV_RAIN      = 7,   // val — 1 начался / 0 закончился
    EV_WIFI      = 8,   // val — 1 подключён / 0 связь потеряна
    EV_AUTH_FAIL = 9,   // val — сколько неудачных входов за минуту
    EV_SETTINGS  = 10,  // arg — EvSettings
    EV_OTA       = 11,  // val — 1 успешно / 0 ошибка
    EV_REBOOT    = 12,  // arg — 0 из панели, 1 плановая
};

enum EvSettings : uint8_t {
    EVS_THRESHOLDS = 0, EVS_TIMER = 1, EVS_WATER = 2, EVS_NETWORK = 3,
    EVS_MQTT = 4, EVS_CREDS = 5, EVS_NTP = 6, EVS_CALIB = 7,
    EVS_FACTORY = 8, EVS_HISTORY_CLEARED = 9,
    EVS_OTA_PASS_SET = 10, EVS_OTA_PASS_OFF = 11,   // пароль ArduinoOTA задан / канал выключен
};

struct __attribute__((packed)) EvRecord {
    uint32_t ts;    // Unix-время; если часы ещё не синхронизированы —
                    // EVLOG_TS_UPTIME | секунды от запуска
    uint8_t  type;  // EvType
    uint8_t  arg;
    int16_t  val;
    uint16_t seq;   // порядковый номер: по нему кольца сливаются в одну ленту
};
#define EVLOG_TS_UPTIME  0x80000000UL

namespace EventLog {

    // Загрузить журнал из NVS и записать событие загрузки. Вызывать
    // в setup() после settingsLoad() — NVS уже инициализирован.
    void init();

    // Добавить событие. Потокобезопасно; можно звать из любой задачи,
    // кроме ISR. Ничего не пишет во флеш — только помечает «есть новое».
    void add(EvType type, uint8_t arg = 0, int16_t val = 0);

    // Неудачная авторизация. Копится и попадает в журнал одним событием
    // раз в минуту — подбор пароля не вытеснит остальные события.
    void authFail();

    // Наблюдатель и отложенное сохранение. Вызывать из taskCore1.
    void loop(uint64_t nowMs);

    // Часы синхронизированы: проставить настоящее время событиям этого
    // запуска, записанным до синхронизации.
    void onTimeSync();

    // Записать в NVS немедленно (перед штатной перезагрузкой).
    void flush();

    // Копия событий в хронологическом порядке. Возвращает количество.
    uint8_t getAll(EvRecord* out, uint8_t maxCount);

}  // namespace EventLog
